    if ($Execute) {
        $logDir = Split-Path $RunLog -Parent
        New-Item -ItemType Directory -Force -Path $logDir | Out-Null
        Add-Content -Path $RunLog -Value $line
    }
}

function Assert-Directory {
    param([string]$Path, [string]$Name)

    if (-not (Test-Path -LiteralPath $Path -PathType Container)) {
        throw "$Name does not exist: $Path"
    }
}

function Ensure-Directory {
    param([string]$Path)

    if (-not $Execute) {
        return
    }

    # Self-heal stale file-vs-directory collisions left by previous
    # orchestration runs.  This is especially important for canonical
    # destinations such as core\confidence, core\execution, and
    # core\lifecycle where an earlier mapping may have created a file with
    # the same basename as the now-required directory.
    if (Test-Path -LiteralPath $Path -PathType Leaf) {
        if ($Force) {
            Write-Log "SELF-HEAL: removing stale file blocking directory: $Path" "WARN"
            Remove-Item -LiteralPath $Path -Force -ErrorAction Stop
        }
        else {
            throw "Target path exists as a file but a directory is required: $Path. Re-run with -Force to self-heal."
        }
    }

    if (Test-Path -LiteralPath $Path -PathType Container) {
        return
    }

    New-Item -ItemType Directory -Force -Path $Path | Out-Null

    if (-not (Test-Path -LiteralPath $Path -PathType Container)) {
        throw "Unable to create required directory: $Path"
    }
}

function Write-TextFile {
    param(
        [string]$Path,
        [string]$Content,
        [switch]$Generated
    )

    $parent = Split-Path $Path -Parent
    Ensure-Directory $parent

    if (Test-Path -LiteralPath $Path) {
        $existing = Get-Content -LiteralPath $Path -Raw -ErrorAction SilentlyContinue
        if (-not $Force -and $existing -and $existing -notmatch [regex]::Escape($Marker)) {
            Write-Log "PROTECTED existing file; not overwriting: $Path" "WARN"
            return
        }
    }

    if ($Execute) {
        Set-Content -LiteralPath $Path -Value $Content -Encoding UTF8
    }
}

function Copy-TreeSafe {
    param(
        [string]$Source,
        [string]$Destination,
        [string]$Label
    )

    Assert-Directory $Source $Label
    Ensure-Directory $Destination

    Write-Log "COPY $Label"
    Write-Log "  FROM: $Source"
    Write-Log "  TO  : $Destination"

    if ($Execute) {
        # robocopy preserves the complete source tree and is substantially safer
        # for large TypeScript/server trees than ad-hoc Get-ChildItem copying.
        $null = & robocopy $Source $Destination /E /COPY:DAT /DCOPY:DAT /R:1 /W:1 /NFL /NDL /NP
        $rc = $LASTEXITCODE
        if ($rc -gt 7) {
            throw "robocopy failed for $Label with exit code $rc"
        }
    }
}

function Get-RelativePath {
    param([string]$Base, [string]$Path)

    # [IO.Path]::GetRelativePath() is .NET Core/.NET 5+ only and does not exist
    # under Windows PowerShell 5.1 (.NET Framework). Use a Uri-based equivalent
    # instead, which works on both runtimes.
    $baseFull = [IO.Path]::GetFullPath($Base)
    $pathFull = [IO.Path]::GetFullPath($Path)

    if (-not $baseFull.EndsWith([IO.Path]::DirectorySeparatorChar)) {
        $baseFull += [IO.Path]::DirectorySeparatorChar
    }

    $baseUri = New-Object System.Uri($baseFull)
    $pathUri = New-Object System.Uri($pathFull)

    $relativeUri = $baseUri.MakeRelativeUri($pathUri)
    $relative = [Uri]::UnescapeDataString($relativeUri.ToString())

    return $relative.Replace("\","/")
}

function Get-TextFiles {
    param([string]$Root)

    if (-not (Test-Path $Root)) { return @() }

    # Directories that must never be walked: dependency trees, build output,
    # VCS metadata, and the migration workspace this script itself generates.
    # Without this, scanning $OpenAlgoFrontend also walks node_modules
    # (tens of thousands of files), which is what causes the scan to appear
    # to hang at Stage 10.
    $excludeDirNames = @(
        "node_modules", ".git", ".hg", ".svn",
        "dist", "build", "out", ".next", ".turbo", ".vite",
        ".cache", "coverage", ".vscode", ".idea",
        "_migration"
    )

    $extensions = @(
        ".ts",".tsx",".js",".jsx",".mjs",".cjs",
        ".json",".css",".scss",".md"
    )

    $stack = New-Object System.Collections.Generic.Stack[string]
    $stack.Push((Get-Item -LiteralPath $Root).FullName)

    $results = New-Object System.Collections.Generic.List[object]

    while ($stack.Count -gt 0) {
        $dir = $stack.Pop()

        try {
            $entries = Get-ChildItem -LiteralPath $dir -Force -ErrorAction Stop
        } catch {
            continue
        }

        foreach ($entry in $entries) {
            if ($entry.PSIsContainer) {
                if ($excludeDirNames -contains $entry.Name) { continue }
                $stack.Push($entry.FullName)
            } elseif ($extensions -contains $entry.Extension) {
                $results.Add($entry)
            }
        }
    }

    return $results
}

function Search-Content {
    param(
        [string]$Root,
        [string[]]$Patterns
    )

    $files = Get-TextFiles $Root
    $results = New-Object System.Collections.Generic.List[object]

    foreach ($file in $files) {
        try {
            $text = Get-Content -LiteralPath $file.FullName -Raw -ErrorAction Stop
        } catch {
            continue
        }

        foreach ($pattern in $Patterns) {
            if ($text -match $pattern) {
                $results.Add([pscustomobject]@{
                    File = Get-RelativePath $Root $file.FullName
                    Pattern = $pattern
                })
            }
        }
    }

    return $results
}

function Get-ImportLines {
    param([string]$Root)

    $results = New-Object System.Collections.Generic.List[object]

    foreach ($file in (Get-TextFiles $Root)) {
        try {
            $lines = Get-Content -LiteralPath $file.FullName -ErrorAction Stop
        } catch {
            continue
        }

        $lineNo = 0
        foreach ($line in $lines) {
            $lineNo++

            if ($line -match '^\s*(import|export)\s+.*?from\s+["''](.+?)["'']') {
                $results.Add([pscustomobject]@{
                    File = Get-RelativePath $Root $file.FullName
                    Line = $lineNo
                    Kind = $Matches[1]
                    Import = $Matches[2]
                })
            }
            elseif ($line -match '^\s*(import)\s*["''](.+?)["'']') {
                $results.Add([pscustomobject]@{
                    File = Get-RelativePath $Root $file.FullName
                    Line = $lineNo
                    Kind = "import"
                    Import = $Matches[2]
                })
            }
        }
    }

    return $results
}

