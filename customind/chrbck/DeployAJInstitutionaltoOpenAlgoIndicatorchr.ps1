function Get-FileTextSafe {
    param([string]$Path)

    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        return $null
    }

    try {
        return [string](Get-Content -LiteralPath $Path -Raw -ErrorAction Stop)
    }
    catch {
        return $null
    }
}

function Get-SourceFilesByName {
    param(
        [string]$Root,
        [string]$Name
    )

    if (-not (Test-Path -LiteralPath $Root -PathType Container)) {
        return @()
    }

    try {
        return @(
            Get-ChildItem `
                -LiteralPath $Root `
                -Recurse `
                -File `
                -Filter $Name `
                -ErrorAction SilentlyContinue |
            Where-Object {
                $_.FullName -notmatch '\\node_modules\\|\\.git\\|\\_migration\\'
            }
        )
    }
    catch {
        return @()
    }
}

function Get-ImportTargets {
    param([string]$FilePath)

    $text = Get-FileTextSafe $FilePath

    if ($null -eq $text) {
        return @()
    }

    $results = @()

    try {
        $matches = [regex]::Matches(
            $text,
            '(?m)\b(?:import|export)\s+(?:type\s+)?(?:[^\r\n]*?\s+from\s+)?["'']([^"'']+)["'']|\brequire\(\s*["'']([^"'']+)["'']\s*\)'
        )

        foreach ($m in $matches) {
            $value = $null

            if ($m.Groups[1].Success) {
                $value = [string]$m.Groups[1].Value
            }
            elseif ($m.Groups[2].Success) {
                $value = [string]$m.Groups[2].Value
            }

            if (
                -not [string]::IsNullOrWhiteSpace($value) -and
                $results -notcontains $value
            ) {
                $results += $value
            }
        }
    }
    catch {
        return @()
    }

    return @($results)
}

function Resolve-LocalTsImport {
    param(
        [string]$Importer,
        [string]$Spec
    )

    if ([string]::IsNullOrWhiteSpace($Spec)) {
        return $null
    }

    if (-not $Spec.StartsWith(".")) {
        return $null
    }

    try {
        $base = Split-Path -Parent $Importer
        $candidate = [IO.Path]::GetFullPath(
            (Join-Path $base $Spec)
        )

        $variants = @(
            $candidate
            "$candidate.ts"
            "$candidate.tsx"
            "$candidate.js"
            "$candidate.jsx"
            (Join-Path $candidate "index.ts")
            (Join-Path $candidate "index.tsx")
            (Join-Path $candidate "index.js")
        )

        foreach ($variant in $variants) {
            if (Test-Path -LiteralPath $variant -PathType Leaf) {
                return $variant
            }
        }
    }
    catch {
        return $null
    }

    return $null
}

