# ------------------------------------------------------------
# HELPER — safe text replacement
# ------------------------------------------------------------

function Replace-AJImportText {
    param(
        [string]$Root,
        [string]$Old,
        [string]$New
    )

    $changed = 0

    $files = @(
        Get-ChildItem -LiteralPath $Root -Recurse -File -ErrorAction SilentlyContinue |
        Where-Object {
            ($_.Extension -eq ".ts" -or
             $_.Extension -eq ".tsx" -or
             $_.Extension -eq ".js" -or
             $_.Extension -eq ".jsx") -and
            $_.FullName -notmatch '\\_migration\\'
        }
    )

    foreach ($file in $files) {

        $text = [System.IO.File]::ReadAllText($file.FullName)

        if ($null -eq $text) {
            continue
        }

        if ($text.Contains($Old)) {

            $newText = $text.Replace($Old, $New)

            if ($newText -ne $text) {

                [System.IO.File]::WriteAllText(
                    $file.FullName,
                    $newText,
                    [System.Text.UTF8Encoding]::new($false)
                )

                $changed++

                Write-Log `
                    "28.5 IMPORT: $($file.Name): '$Old' -> '$New'" `
                    "INFO"
            }
        }
    }

    return $changed
}

# ------------------------------------------------------------
# HELPER — safe file move/merge
# ------------------------------------------------------------

function Merge-AJFolder {
    param(
        [string]$Source,
        [string]$Destination
    )

    if (-not (Test-Path -LiteralPath $Source -PathType Container)) {
        return
    }

    if (-not (Test-Path -LiteralPath $Destination -PathType Container)) {
        New-Item -ItemType Directory -Path $Destination -Force | Out-Null
    }

    $items = @(
        Get-ChildItem -LiteralPath $Source -Force -ErrorAction SilentlyContinue
    )

    foreach ($item in $items) {

        $destinationItem = Join-Path $Destination $item.Name

        if ($item.PSIsContainer) {

            Merge-AJFolder `
                -Source $item.FullName `
                -Destination $destinationItem

        }
        else {

            if (-not (Test-Path -LiteralPath $destinationItem)) {

                Move-Item `
                    -LiteralPath $item.FullName `
                    -Destination $destinationItem `
                    -Force

            }
            else {

                Write-Log `
                    "28.5 MERGE: destination already exists, preserving destination: $destinationItem" `
                    "WARN"
            }
        }
    }

    if (Test-Path -LiteralPath $Source -PathType Container) {

        $remaining = @(
            Get-ChildItem -LiteralPath $Source -Force -ErrorAction SilentlyContinue
        )

        if ($remaining.Count -eq 0) {
            Remove-Item -LiteralPath $Source -Recurse -Force
        }
    }
}

# ============================================================
# 28.5 DIRECTORY SAFETY HELPER
# ============================================================

function Ensure-DirectoryPath {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Path
    )

    if ([string]::IsNullOrWhiteSpace($Path)) {
        return
    }

    if (Test-Path -LiteralPath $Path) {
        $existing = Get-Item -LiteralPath $Path -Force -ErrorAction Stop

        if (-not $existing.PSIsContainer) {
            throw "Expected directory but found a file: $Path"
        }

        return
    }

    New-Item -ItemType Directory -Path $Path -Force -ErrorAction Stop | Out-Null
}

