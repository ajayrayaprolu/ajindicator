function Port-ContractFile {
    param(
        [string]$OriginalRelPath,   # relative to $OriginalSrc
        [string]$TargetRelPath,     # relative to $BuildRoot
        [string]$Reason
    )

    $sourcePath = Join-Path $OriginalSrc $OriginalRelPath
    $targetPath = Join-Path $BuildRoot $TargetRelPath

    if (-not (Test-Path -LiteralPath $sourcePath -PathType Leaf)) {
        Write-Log "Contract source not found, cannot port: $OriginalRelPath" "WARN"
        Register-Skip -OriginalRelPath $OriginalRelPath -Kind "PORT-CONTRACT" -Reason "Source file not found"
        return
    }

    $original = Get-Content -LiteralPath $sourcePath -Raw

    # Detect relative imports so we can flag which ones still need resolving
    # once their target files exist in the new tree. We do NOT rewrite these
    # automatically - the import-rewrite policy explicitly forbids blind
    # regex replacement. We only report what needs a decision.
    $importLines = @([regex]::Matches($original, 'import\s+.*?from\s+["''](\.[^"'']+)["''];?') |
        ForEach-Object { $_.Groups[1].Value })

    $flagBlock = ""
    if ($importLines.Count -gt 0) {
        $flagBlock = "`n * UNRESOLVED RELATIVE IMPORTS (original paths - must be re-pointed`n" +
                     " * at their new /indicators/AJInstitutional location once each`n" +
                     " * target is ported; see reports/09.migration-status-table.md):`n"
        foreach ($imp in $importLines) {
            $flagBlock += " *   - $imp`n"
        }
    }

    $header = @"
/**
 * $Marker
 * PORTED VERBATIM from original: $OriginalRelPath
 * Reason: $Reason
 *
 * Field names below are UNCHANGED from the original AJ source on purpose -
 * engine code (AJRuntimeContextBuilder, AJDecisionEngine, etc.) was written
 * against these exact field names (e.g. candle.time, not candle.timestamp).
 * Renaming fields here without also updating every consumer reintroduces
 * the "silently becomes undefined/0" class of bug this migration exists to
 * fix. Add OpenAlgo-specific fields as additive optional fields only.
$flagBlock */

"@

    Write-TextFile $targetPath ($header + $original) -Generated
    Register-Copy -OriginalRelPath $OriginalRelPath -NewRelPath $TargetRelPath -Kind "PORT-CONTRACT"
    Write-Log "  $OriginalRelPath -> $TargetRelPath (ported verbatim, $($importLines.Count) import(s) flagged)"
}

