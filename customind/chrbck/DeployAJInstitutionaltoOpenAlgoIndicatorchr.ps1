.SYNOPSIS
    Builds a FRESH AJInstitutional implementation for the OpenAlgo React/TypeScript
    frontend from the original AJInstitutional source tree.

.DESCRIPTION
    This is an orchestration/deployment script, not a "copy one JS indicator" script.

    SOURCE OF TRUTH
      Original AJIndicator source : C:\AI-Institutional\src
      Original AJ server source   : C:\AI-Institutional\server
      OpenAlgo frontend            : C:\AJMultiAlgo\fyersopenalgo\frontend

    DESIGN RULE
      - Original AJ logic is preserved as the behavioral source of truth.
      - OpenAlgo supplies market data, candles, chart identity, settings persistence,
        and platform services.
      - The AJ engine is rebuilt as a frontend TypeScript module.
      - Broker/server-specific code is NEVER blindly executed in the browser.
      - Original source is copied into an immutable migration snapshot for reference.
      - Existing OpenAlgo frontend files are NOT overwritten by default.
      - The script creates manifests, mappings, import reports, adapter contracts,
        and a build plan so implementation/debugging can proceed stage-by-stage.

    IMPORTANT
      This script intentionally does NOT claim that a semantic source-to-frontend
      port can be completed safely by filename copying alone. It creates the complete
      migration workspace and all deterministic scaffolding first. The actual
      behavioral port is then performed against the generated mapping/report.

.PARAMETER BuildRoot
    Root folder for the new indicator module.
    Default:
      C:\AJMultiAlgo\fyersopenalgo\frontend\src\indicators\AJInstitutional

.PARAMETER Execute
    Actually create/copy files. Without -Execute, the script performs a plan-only
    validation and reports what it WOULD do.

.PARAMETER Force
    Allows replacement of files previously generated by this script.
    Existing non-generated OpenAlgo files are still protected.

.PARAMETER PreserveExistingOpenAlgoAdapter
    If the existing OpenAlgoAdapter.ts exists in the frontend, copy it as a baseline
    into the migration snapshot for comparison instead of overwriting it.

.EXAMPLE
    .\DeployAJInstitutionaltoOpenAlgoIndicator.ps1

    Safe PLAN mode.

.EXAMPLE
    .\DeployAJInstitutionaltoOpenAlgoIndicator.ps1 -Execute

    Builds the migration workspace.

.EXAMPLE
