function Copy-FolderPort {
    param(
        [string]$SourceRel,   # relative to $OriginalSrc
        [string]$TargetRel,   # relative to $BuildRoot
        [string]$Confidence = "HIGH",  # HIGH = matches frozen architecture directly; REVIEW = grouping is a judgment call
        [string]$Note = ""
    )

    $sourceFull = Join-Path $OriginalSrc $SourceRel
    $targetFull = Join-Path $BuildRoot $TargetRel

    if (-not (Test-Path -LiteralPath $sourceFull -PathType Container)) {
        Write-Log "P1 source folder not found, skipping: $SourceRel" "WARN"
        Register-Skip -OriginalRelPath $SourceRel -Kind "PORT-P1" -Reason "Source folder not found"
        return
    }

    Ensure-Directory $targetFull

    if ($Execute) {
        # Robocopy returns 16 for a fatal destination condition.  Before
        # failing the whole orchestration, diagnose the destination and
        # self-heal the known stale file/directory collision.
        $robocopySucceeded = $false

        for ($attempt = 1; $attempt -le 2; $attempt++) {

            # A prior run can leave a FILE where this mapping requires a
            # DIRECTORY.  Ensure-Directory normally repairs this, but repeat
            # the check immediately before robocopy so the copy stage is
            # independently self-healing.
            if (Test-Path -LiteralPath $targetFull -PathType Leaf) {
                if ($Force) {
                    Write-Log "SELF-HEAL: destination collision detected before robocopy: $targetFull" "WARN"
                    Remove-Item -LiteralPath $targetFull -Force -ErrorAction Stop
                    Ensure-Directory $targetFull
                }
                else {
                    throw "Destination collision: file exists where directory is required: $targetFull. Re-run with -Force."
                }
            }

            if (-not (Test-Path -LiteralPath $targetFull -PathType Container)) {
                Ensure-Directory $targetFull
            }

            Write-Log "P1 COPY DEBUG: robocopy attempt $attempt for $SourceRel -> $TargetRel" "INFO"
            $null = & robocopy $sourceFull $targetFull /E /COPY:DAT /DCOPY:DAT /R:1 /W:1 /NFL /NDL /NP
            $rc = $LASTEXITCODE

            Write-Log "P1 COPY DEBUG: robocopy exit code = $rc" "INFO"

            if ($rc -le 7) {
                $robocopySucceeded = $true
                break
            }

            if ($rc -gt 7 -and $attempt -eq 1 -and $Force) {
                # Last-resort repair for a stale/broken destination container.
                # Only the TARGET container is touched; the original source is
                # never modified.
                Write-Log "SELF-HEAL: robocopy reported fatal destination error ($rc); resetting target container: $targetFull" "WARN"
                if (Test-Path -LiteralPath $targetFull) {
                    Remove-Item -LiteralPath $targetFull -Recurse -Force -ErrorAction Stop
                }
                Ensure-Directory $targetFull
                continue
            }

            throw "robocopy failed for $SourceRel -> $TargetRel with exit code $rc"
        }

        if (-not $robocopySucceeded) {
            throw "robocopy failed for $SourceRel -> $TargetRel after self-heal retry"
        }
    }

    $fileCount = 0
    foreach ($file in (Get-ChildItem -LiteralPath $sourceFull -Recurse -File -ErrorAction SilentlyContinue)) {
        $rel = Get-RelativePath $sourceFull $file.FullName
        Register-Copy -OriginalRelPath (Join-Path $SourceRel $rel) -NewRelPath (Join-Path $TargetRel $rel) -Kind "PORT-P1"
        $fileCount++
    }

    if ($Confidence -eq "REVIEW") {
        Write-Log "  $SourceRel -> $TargetRel ($fileCount files) [REVIEW: $Note]" "WARN"
    } else {
        Write-Log "  $SourceRel -> $TargetRel ($fileCount files)"
    }
}

