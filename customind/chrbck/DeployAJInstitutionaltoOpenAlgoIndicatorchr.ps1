Write-Log "STAGE 36 DEBUG: frontend = $OpenAlgoFrontend" "INFO"
Write-Log "STAGE 36 DEBUG: running npm run build" "INFO"

try {

    if (-not (Test-Path -LiteralPath $OpenAlgoFrontend -PathType Container)) {
        throw "OpenAlgo frontend directory does not exist: $OpenAlgoFrontend"
    }

    $npmCommand = Get-Command npm.cmd -ErrorAction SilentlyContinue

    if ($null -eq $npmCommand) {
        $npmCommand = Get-Command npm -ErrorAction SilentlyContinue
    }

    if ($null -eq $npmCommand) {
        throw "npm executable was not found in PATH."
    }

    Push-Location $OpenAlgoFrontend

    try {

        $stdoutFile = Join-Path $env:TEMP ("AJInstitutional-npm-build-" + [guid]::NewGuid().ToString("N") + ".stdout.log")
        $stderrFile = Join-Path $env:TEMP ("AJInstitutional-npm-build-" + [guid]::NewGuid().ToString("N") + ".stderr.log")

        try {

            # Windows PowerShell can convert a native command's stderr
            # output into a terminating exception when
            # $ErrorActionPreference = "Stop" (set globally at the top of
            # this script) - even for harmless lines like npm's own
            # "npm notice run <pkg> build" lifecycle message. Relax it for
            # just this call so a real build failure is judged by exit
            # code / compiler output, not by npm writing anything at all
            # to stderr.
            $previousEap = $ErrorActionPreference
            $ErrorActionPreference = "Continue"
            try {
                & $npmCommand.Source run build `
                    1> $stdoutFile `
                    2> $stderrFile
                $buildExitCode = $LASTEXITCODE
            }
            finally {
                $ErrorActionPreference = $previousEap
            }

            $stdout = ""

            if (Test-Path -LiteralPath $stdoutFile) {
                $stdout = [System.IO.File]::ReadAllText($stdoutFile)
            }

            $stderr = ""

            if (Test-Path -LiteralPath $stderrFile) {
                $stderr = [System.IO.File]::ReadAllText($stderrFile)
            }

            $combinedOutput =
                @(
                    $stdout
                    $stderr
                ) -join [Environment]::NewLine

            $buildResult.ExitCode       = $buildExitCode
            $buildResult.StdOut         = $stdout
            $buildResult.StdErr         = $stderr
            $buildResult.CombinedOutput = $combinedOutput

            $buildResult.UnresolvedImports =
                @(
                    $combinedOutput -split "`r?`n" |
                    Where-Object {
                        $_ -match "Cannot find module|Module not found|Could not resolve|does not exist"
                    }
                )

            $buildResult.TypeScriptErrors =
                @(
                    $combinedOutput -split "`r?`n" |
                    Where-Object {
                        $_ -match "TS\d{3,5}"
                    }
                )

            $buildResult.BuildErrors =
                @(
                    $combinedOutput -split "`r?`n" |
                    Where-Object {
                        $_ -match "error|ERROR|failed|FAIL"
                    }
                )

            if ($buildExitCode -eq 0) {

                $buildResult.Status = "PASS"
                $buildResult.BuildSucceeded = $true

                Write-Log "STAGE 36: npm run build = PASS" "INFO"
                Write-Log "STAGE 36: npm exit code = 0" "INFO"

            }
            else {

                $buildResult.Status = "FAIL"
                $buildResult.BuildSucceeded = $false

                Write-Log "STAGE 36: npm run build = FAIL" "ERROR"
                Write-Log "STAGE 36: npm exit code = $buildExitCode" "ERROR"

                Write-Log `
                    "STAGE 36: unresolved/module errors captured = $(@($buildResult.UnresolvedImports).Count)" `
                    "ERROR"

                Write-Log `
                    "STAGE 36: TypeScript errors captured = $(@($buildResult.TypeScriptErrors).Count)" `
                    "ERROR"

            }

        }
        finally {

            if (Test-Path -LiteralPath $stdoutFile) {
                Remove-Item -LiteralPath $stdoutFile -Force -ErrorAction SilentlyContinue
            }

            if (Test-Path -LiteralPath $stderrFile) {
                Remove-Item -LiteralPath $stderrFile -Force -ErrorAction SilentlyContinue
            }
        }
    }
    finally {

        Pop-Location
    }

}
catch {

    $buildResult.Status = "FAIL"
    $buildResult.BuildSucceeded = $false
    $buildResult.StdErr = $_.Exception.Message
    $buildResult.CombinedOutput = $_.Exception.ToString()

    Write-Log "STAGE 36: build execution exception" "ERROR"
    Write-Log $_.Exception.Message "ERROR"
}

