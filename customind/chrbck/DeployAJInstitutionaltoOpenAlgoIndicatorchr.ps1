# 23. AUTOMATED CONTRACT FIELD-USAGE VALIDATION
# ============================================================
#
# This replaces manually running Select-String and eyeballing diffs.
# It only works meaningfully in -Execute mode, since it inspects the actual
# files written into $BuildRoot. In plan mode it still runs but reports
# NOT_YET_COPIED for everything, which is expected and not an error.

Write-Log "23. Validating field usage in ported engine files against ported contracts"

function Get-InterfaceFieldNames {
    param([string]$FilePath)

    if (-not (Test-Path -LiteralPath $FilePath -PathType Leaf)) { return @() }

    $text = Get-Content -LiteralPath $FilePath -Raw
    # Get-Content -Raw returns $null (not "") for a genuinely empty file -
    # guard before calling any string method on it.
    if ([string]::IsNullOrEmpty($text)) { return @() }

    # Grab the first top-level "export interface X { ... }" block by brace
    # counting (good enough for these files - no nested interfaces observed).
    $startIdx = $text.IndexOf("interface")
    if ($startIdx -lt 0) { return @() }

    $openIdx = $text.IndexOf("{", $startIdx)
    if ($openIdx -lt 0) { return @() }

    $depth = 0
    $endIdx = -1
    for ($i = $openIdx; $i -lt $text.Length; $i++) {
        if ($text[$i] -eq '{') { $depth++ }
        elseif ($text[$i] -eq '}') {
            $depth--
            if ($depth -eq 0) { $endIdx = $i; break }
        }
    }
    if ($endIdx -lt 0) { return @() }

    $body = $text.Substring($openIdx + 1, $endIdx - $openIdx - 1)

    # Field lines look like:  fieldName: Type;   or   fieldName?: Type;
    $fields = @([regex]::Matches($body, '(?m)^\s*([A-Za-z_][A-Za-z0-9_]*)\??\s*:') |
        ForEach-Object { $_.Groups[1].Value } |
        Select-Object -Unique)

    return $fields
}

function Test-FieldUsage {
    param(
        [string]$ContractPath,
        [string[]]$VarNamePatterns,   # e.g. @("candle","current","previous")
        [string[]]$ScanPaths,         # actual files to scan for usage
        [string]$ContractLabel,
        [string]$RequireTypeHint = "",  # e.g. "Candle" - skip files that never
                                       # mention this type name at all, since
                                       # generic var names like "current" are
                                       # reused across unrelated object types
                                       # (e.g. a debug/trace snapshot) and a
                                       # file that never references the type
                                       # is almost certainly not using that
                                       # variable name for it here.
        [string]$ExcludeIfMentions = "" # e.g. "AJRuntimeContext" - skip files
                                       # that reference a DIFFERENT, similarly
                                       # named type. "AJRuntimeContext" contains
                                       # "RuntimeContext" as a substring, so
                                       # RequireTypeHint alone can't separate
                                       # base RuntimeContext usage from the
                                       # enriched AJRuntimeContext type.
    )

    $fields = Get-InterfaceFieldNames -FilePath $ContractPath
    # Note: an empty array returned across a function boundary can arrive
    # here as $null (PowerShell output-stream unwrapping), and under
    # Set-StrictMode -Version Latest, "$null.Count" throws instead of
    # quietly returning nothing. Check for $null first so this never touches
    # .Count on a possibly-null value.
    if (-not $fields -or $fields.Count -eq 0) {
        Write-Log "  [$ContractLabel] contract not found or has no parsable interface yet - skipping usage check" "WARN"
        return @()
    }

    $varAlt = ($VarNamePatterns -join "|")
    $pattern = "\b($varAlt)\.([A-Za-z_][A-Za-z0-9_]*)\b"
    $mismatches = New-Object System.Collections.Generic.List[object]

    foreach ($path in $ScanPaths) {
        if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { continue }
        $text = Get-Content -LiteralPath $path -Raw
        # Same null-on-empty-file issue as Get-InterfaceFieldNames: some
        # ported files are genuinely 0 bytes in the original source, and
        # [regex]::Matches($null, ...) throws ArgumentNullException instead
        # of just finding no matches.
        if ([string]::IsNullOrEmpty($text)) { continue }
        if ($RequireTypeHint -and ($text -notmatch [regex]::Escape($RequireTypeHint))) {
            continue
        }
        if ($ExcludeIfMentions -and ($text -match [regex]::Escape($ExcludeIfMentions))) {
            continue
        }
        foreach ($m in [regex]::Matches($text, $pattern)) {
            $field = $m.Groups[2].Value
            if ($fields -notcontains $field) {
                $mismatches.Add([pscustomobject]@{
                    Contract = $ContractLabel
                    File     = $path
                    Accessed = "$($m.Groups[1].Value).$field"
                    Field    = $field
                })
            }
        }
    }

    return $mismatches
}

