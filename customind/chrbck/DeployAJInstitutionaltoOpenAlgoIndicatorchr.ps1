function Get-AJSafePath {
    param(
        [AllowNull()]
        $Item
    )

    if ($null -eq $Item) {
        return $null
    }

    if ($Item -is [string]) {
        if (-not [string]::IsNullOrWhiteSpace($Item)) {
            return [string]$Item
        }
        return $null
    }

    if ($Item.PSObject.Properties["FullName"]) {
        $value = $Item.PSObject.Properties["FullName"].Value

        if ($null -ne $value -and
            -not [string]::IsNullOrWhiteSpace([string]$value)) {
            return [string]$value
        }
    }

    if ($Item.PSObject.Properties["Path"]) {
        $value = $Item.PSObject.Properties["Path"].Value

        if ($null -ne $value -and
            -not [string]::IsNullOrWhiteSpace([string]$value)) {
            return [string]$value
        }
    }

    return $null
}

function Get-AJTsxFilesSafe {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Root
    )

    if (-not (Test-Path -LiteralPath $Root -PathType Container)) {
        return @()
    }

    $result = New-Object System.Collections.Generic.List[string]

    $items = @(
        Get-ChildItem `
            -LiteralPath $Root `
            -Recurse `
            -File `
            -ErrorAction SilentlyContinue |
        Where-Object {
            $_.Extension -eq ".ts" -or
            $_.Extension -eq ".tsx"
        }
    )

    foreach ($item in $items) {

        $safePath = Get-AJSafePath $item

        if ($null -eq $safePath) {
            continue
        }

        if (-not (Test-Path -LiteralPath $safePath -PathType Leaf)) {
            continue
        }

        $result.Add($safePath)
    }

    return @($result)
}

function Repair-AJFileImports {
    param(
        [Parameter(Mandatory = $true)]
        [string]$FilePath,

        [Parameter(Mandatory = $true)]
        [hashtable]$Replacements
    )

    if (-not (Test-Path -LiteralPath $FilePath -PathType Leaf)) {
        return $false
    }

    $text = [System.IO.File]::ReadAllText($FilePath)

    if ($null -eq $text) {
        return $false
    }

    $original = $text

    foreach ($key in $Replacements.Keys) {

        $replacement = $Replacements[$key]

        if ($null -eq $replacement) {
            continue
        }

        if ($text.Contains([string]$key)) {

            $text = $text.Replace(
                [string]$key,
                [string]$replacement
            )
        }
    }

    if ($text -eq $original) {
        return $false
    }

    [System.IO.File]::WriteAllText(
        $FilePath,
        $text,
        [System.Text.UTF8Encoding]::new($false)
    )

    Write-Log `
        "28.5 CONTRACT REPAIR: $FilePath" `
        "INFO"

    return $true
}

