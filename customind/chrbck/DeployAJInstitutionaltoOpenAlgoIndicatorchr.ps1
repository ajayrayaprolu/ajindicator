function Find-SourceReferences {
    param(
        [string]$Root,
        [string[]]$Patterns
    )

    $rows = New-Object System.Collections.Generic.List[object]

    foreach ($file in Get-AllTsFiles $Root) {
        $text = Get-TextSafe $file.FullName
        if (-not $text) {
            continue
        }

        foreach ($pattern in $Patterns) {
            if ($text -match $pattern) {
                $rows.Add([pscustomobject]@{
                    File    = Get-RelativeSafe $Root $file.FullName
                    Pattern = $pattern
                })
            }
        }
    }

    return $rows.ToArray()
}

function Get-ExportedSymbols {
    param([string]$Text)

    $symbols = New-Object System.Collections.Generic.List[string]

    foreach ($m in [regex]::Matches(
        $Text,
        '(?m)\bexport\s+(?:default\s+)?(?:class|interface|type|enum|function|const|let|var)\s+([A-Za-z_][A-Za-z0-9_]*)'
    )) {
        if (-not $symbols.Contains($m.Groups[1].Value)) {
            $symbols.Add($m.Groups[1].Value)
        }
    }

    return $symbols.ToArray()
}

function Get-ImportedSymbolEvidence {
    param(
        [string]$Root,
        [string]$Symbol
    )

    $rows = New-Object System.Collections.Generic.List[object]

    foreach ($file in Get-AllTsFiles $Root) {
        $text = Get-TextSafe $file.FullName
        if (-not $text) {
            continue
        }

        if ($text -match "(?m)\b$([regex]::Escape($Symbol))\b") {
            $rows.Add([pscustomobject]@{
                File = Get-RelativeSafe $Root $file.FullName
            })
        }
    }

    return $rows.ToArray()
}

